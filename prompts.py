def narration_facts(title: str, facts: list[str], extra: str = "") -> str:
    lines = [f"场景:{title}", "既成事实:"]
    lines += [f"- {f}" for f in facts if f]
    if extra:
        lines.append(f"补充:{extra}")
    return "\n".join(lines)
